/**
 * A guide for every block: right-click a block -> "What does this block do?".
 * Each entry: a short explanation, a "Try:" idea and a small example program.
 * The example is real TypeScript; the build turns it into blocks (src/webview/help.data.json)
 * and the tests check it converts cleanly and runs.
 */

export interface HelpText {
  title: string;
  text: string;
  tip: string;
}

export interface BlockHelp {
  type: string;
  cs: HelpText;
  en: HelpText;
  code: string;
  /** false = the example cannot run inside the help window (e.g. it imports another file) */
  run?: boolean;
  /** the example is allowed to contain raw-code blocks (the "TS code" blocks themselves) */
  raw?: boolean;
}

const L = (...lines: string[]) => lines.join('\n') + '\n';
const h = (type: string, cs: [string, string, string], en: [string, string, string], code: string, opts: { run?: boolean; raw?: boolean } = {}): BlockHelp => ({
  type,
  cs: { title: cs[0], text: cs[1], tip: cs[2] },
  en: { title: en[0], text: en[1], tip: en[2] },
  code,
  ...opts,
});

